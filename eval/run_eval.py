"""Run the DocQ evaluation. Everything printed/written here is computed by this script.

    python eval/run_eval.py            # writes eval/results.json and eval/RESULTS.md
    python eval/run_eval.py --dev      # prints dev-set confidence scores (used to pick MIN_SCORE)
"""
import json, statistics, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from docq import answer, config
from docq.ingest import chunk_document, extract_pages
from docq.retrieval import build_retriever

KS = (1, 3, 5)


def load_chunks():
    chunks = []
    for p in sorted((ROOT / "sample_docs").glob("*.pdf")):
        chunks += chunk_document(p.name, extract_pages(p.name, p.read_bytes()), config.CHUNK_WORDS)
    return chunks


def norm(s): return s.lower().replace(",", "")


def page_ranking(retriever, question, depth=10):
    pages = []
    for c, _ in retriever.search(question, depth):
        key = (c.doc, c.page)
        if key not in pages:
            pages.append(key)
    return pages


def eval_mode(mode, qs):
    chunks = load_chunks()
    r = build_retriever(chunks, mode, config.EMBED_MODEL)
    hits = {k: 0 for k in KS}; rr = []; cite_ok = 0; kw_ok = 0; both_ok = 0; false_abstain = 0; lat = []
    per_q = []
    for q in qs["answerable"]:
        gold = (q["doc"], q["page"])
        ranking = page_ranking(r, q["question"])
        rank = ranking.index(gold) + 1 if gold in ranking else None
        for k in KS:
            hits[k] += bool(rank and rank <= k)
        rr.append(1 / rank if rank else 0.0)
        t = time.perf_counter(); res = answer.ask(r, q["question"]); lat.append((time.perf_counter() - t) * 1000)
        cited = [(c["doc"], c["page"]) for c in res["citations"]]
        c_ok = gold in cited
        k_ok = all(norm(m) in norm(res["answer"]) for m in q["must_contain"]) and not res["abstained"]
        cite_ok += c_ok; kw_ok += k_ok; both_ok += (c_ok and k_ok); false_abstain += res["abstained"]
        per_q.append({"q": q["question"], "gold": f"{q['doc']} p.{q['page']}", "rank": rank, "cited": [f"{d} p.{p}" for d, p in cited],
                      "citation_ok": c_ok, "answer_has_fact": k_ok, "abstained": res["abstained"], "answer": res["answer"]})
    n = len(qs["answerable"])
    oos_abstain = sum(answer.ask(r, q)["abstained"] for q in qs["out_of_scope"])
    return {"retriever": mode, "n_answerable": n, "n_out_of_scope": len(qs["out_of_scope"]),
            **{f"hit@{k}": hits[k] / n for k in KS}, "MRR": sum(rr) / n,
            "citation_accuracy": cite_ok / n, "answer_contains_expected_fact": kw_ok / n, "cited_and_correct": both_ok / n,
            "false_abstain_rate": false_abstain / n, "out_of_scope_abstained": f"{oos_abstain}/{len(qs['out_of_scope'])}",
            "median_ask_latency_ms": round(statistics.median(lat), 1)}, per_q


def dev_scores():
    dev = json.load(open(ROOT / "eval" / "dev_questions.json"))
    r = build_retriever(load_chunks(), "dense", config.EMBED_MODEL)
    for grp in ("answerable", "out_of_scope"):
        for q in dev[grp]:
            text = q["question"] if isinstance(q, dict) else q
            print(f"{grp:13s} conf={r.confidence(text):.3f}  {text}")


def main():
    if "--dev" in sys.argv:
        return dev_scores()
    qs = json.load(open(ROOT / "eval" / "questions.json"))
    results, details = [], {}
    for mode in ("bm25", "dense", "hybrid"):
        res, per_q = eval_mode(mode, qs); results.append(res); details[mode] = per_q
    default = config.RETRIEVER if config.RETRIEVER != "auto" else "hybrid"
    out = {"embedding_model": config.EMBED_MODEL, "min_score": config.MIN_SCORE, "chunk_words": config.CHUNK_WORDS,
           "corpus": {"documents": 5, "pages": 18}, "generator": "extractive", "default_retriever": default,
           "results": results, "details": details}
    json.dump(out, open(ROOT / "eval" / "results.json", "w"), indent=1)
    cols = ["retriever", "hit@1", "hit@3", "hit@5", "MRR", "citation_accuracy", "answer_contains_expected_fact", "cited_and_correct", "false_abstain_rate", "out_of_scope_abstained", "median_ask_latency_ms"]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in results:
        lines.append("| " + " | ".join(f"{r[c]:.2f}" if isinstance(r[c], float) else str(r[c]) for c in cols) + " |")
    md = ("# DocQ evaluation (auto-generated by eval/run_eval.py)\n\n"
          f"Measured on my test set of {results[0]['n_answerable']} answerable questions + {results[0]['n_out_of_scope']} out-of-scope questions, "
          "over 5 fictional documents (18 pages) written by the author. Generator: extractive. "
          f"Embedding model: {config.EMBED_MODEL}. Abstention threshold (dense cosine) {config.MIN_SCORE}.\n\n" + "\n".join(lines) + "\n")
    (ROOT / "eval" / "RESULTS.md").write_text(md)
    print(md)
    for mode in ("dense",):
        miss = [d for d in details[mode] if not d["citation_ok"]]
        print(f"[{mode}] questions without a correct citation:", [d["q"] for d in miss])

if __name__ == "__main__":
    main()
